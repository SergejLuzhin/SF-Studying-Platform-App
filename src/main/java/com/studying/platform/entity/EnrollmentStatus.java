package com.studying.platform.entity;

/**
 * Перечисление статусов записи на курс.
 * <p>
 * Определяет два основных статуса: активная запись и отписка.
 * Используется в качестве типа для поля {@code status} сущности {@link Enrollment}.
 * </p>
 */
public enum EnrollmentStatus {

    /**
     * Студент активно записан на курс.
     */
    ACTIVE,

    /**
     * Студент отписался от курса (история сохраняется).
     */
    DROPPED
}
