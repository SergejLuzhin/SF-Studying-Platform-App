package com.studying.platform.entity;

/**
 * Перечисление типов вопросов викторины.
 * <p>
 * Определяет два типа вопросов: с единственным правильным ответом
 * и с множественным выбором. Используется в качестве типа
 * для поля {@code type} сущности {@link Question}.
 * </p>
 *
 * @see Question
 */
public enum QuizQuestionType {

    /**
     * Вопрос с единственным правильным ответом.
     */
    SINGLE_CHOICE,

    /**
     * Вопрос с множественным выбором (может быть несколько правильных вариантов).
     */
    MULTIPLE_CHOICE
}
