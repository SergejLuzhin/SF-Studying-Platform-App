package com.studying.platform.entity;

/**
 * Перечисление ролей пользователя учебной платформы.
 * <p>
 * Определяет три основные роли: студент, преподаватель и администратор.
 * Используется в качестве типа для поля {@code role} сущности {@link User}.
 * </p>
 */
public enum UserRole {

    /**
     * Студент — может записываться на курсы, отправлять решения,
     * проходить тесты и оставлять отзывы.
     */
    STUDENT,

    /**
     * Преподаватель — может создавать и вести курсы,
     * добавлять модули, уроки, задания и оценивать решения.
     */
    TEACHER,

    /**
     * Администратор — резервная роль для будущих расширений платформы.
     */
    ADMIN
}
